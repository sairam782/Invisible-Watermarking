"""Build an arXiv-compatible submission package.

arXiv accepts a tarball/zip containing the LaTeX source, bibliography,
and figure files. No binary .pdf (it is generated by arXiv's build
server), no .bbl, no auxiliary files.

This script assembles everything under /tmp/scratchpad/arxiv_package/
and zips it.
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path
import zipfile

REPO_ROOT = Path(__file__).resolve().parent.parent
PAPER_DIR = REPO_ROOT / "paper"


def build_package(out_dir: Path, include_bbl: bool = True):
    """Assemble the arXiv source tree at `out_dir` and zip it."""
    out_dir.mkdir(parents=True, exist_ok=True)

    # Clean any prior copy.
    for p in out_dir.iterdir():
        if p.is_dir():
            shutil.rmtree(p)
        else:
            p.unlink()

    # Copy main.tex, bib, figures/.
    shutil.copy(PAPER_DIR / "main.tex", out_dir / "main.tex")
    shutil.copy(PAPER_DIR / "references.bib", out_dir / "references.bib")
    (out_dir / "figures").mkdir(exist_ok=True)
    # Only the figures main.tex actually includes.
    import re
    tex = (PAPER_DIR / "main.tex").read_text()
    for name in re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{figures/([^}]+)\}", tex):
        shutil.copy(PAPER_DIR / "figures" / name, out_dir / "figures" / name)
    # Generated tables pulled in with \input{tables/...}.
    shutil.copytree(PAPER_DIR / "tables", out_dir / "tables")
    # arXiv is happier with .bbl alongside .bib for reproducibility.
    if include_bbl and (PAPER_DIR / "main.bbl").exists():
        shutil.copy(PAPER_DIR / "main.bbl", out_dir / "main.bbl")

    # A short cover note helps the moderators.
    (out_dir / "README.txt").write_text(
        "Distribution-Preserving QIM: Trading Noise Margin for Statistical\n"
        "Undetectability and Scaling Robustness in Invisible Watermarking\n"
        "\n"
        "Author: Abhishek Sairam Gaduputi (New Jersey Institute of Technology)\n"
        "\n"
        "Build: pdflatex main.tex && bibtex main && pdflatex main.tex\n"
        "  && pdflatex main.tex\n"
        "\n"
        "Primary category: cs.CR (cryptography and security)\n"
        "Cross-list:       cs.CV (computer vision)\n"
        "\n"
        "Code: https://github.com/sairam782/Invisible-Watermarking\n"
    )

    # Zip
    zip_path = out_dir.parent / f"{out_dir.name}.zip"
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in out_dir.rglob("*"):
            if path.is_file():
                zf.write(path, path.relative_to(out_dir.parent))
    print(f"wrote {out_dir}")
    print(f"wrote {zip_path}  ({zip_path.stat().st_size // 1024} KB)")
    print()
    print("Contents:")
    for path in sorted(out_dir.rglob("*")):
        if path.is_file():
            print(f"  {path.relative_to(out_dir.parent)}  "
                   f"({path.stat().st_size // 1024} KB)")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="/tmp/claude-0/arxiv_package",
                    help="output directory (the .zip will live alongside)")
    args = ap.parse_args()
    build_package(Path(args.out))


if __name__ == "__main__":
    main()
